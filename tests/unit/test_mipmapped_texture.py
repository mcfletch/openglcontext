"""MMTexture, the texture an MMImageTexture draws with, carries its mipmap chain.

The chain is generated by GL from the image stored at level 0, in the same
sized formats a plain Texture uses, so it is drawn in a core profile as well
as a compatibility one.
"""
import numpy as np
import pytest
from OpenGL import GL as gl

PIL = pytest.importorskip('PIL.Image')

from OpenGLContext import texture


def _image(mode='RGB', size=8):
    channels = {'RGB': 3, 'L': 1}[mode]
    data = np.full((size, size, channels), 200, dtype='B')
    return PIL.fromarray(data.squeeze(), mode)


def _level_width(level):
    return int(gl.glGetTexLevelParameteriv(gl.GL_TEXTURE_2D, level, gl.GL_TEXTURE_WIDTH))


@pytest.mark.parametrize('fixture', ['gl_context', 'gl_context_compat'])
def test_every_level_of_the_chain_is_stored(fixture, request):
    request.getfixturevalue(fixture)
    texture.MMTexture(_image(size=8)).bind()
    assert [_level_width(level) for level in range(4)] == [8, 4, 2, 1]
    assert gl.glGetError() == gl.GL_NO_ERROR


@pytest.mark.usefixtures('gl_context')
def test_a_greyscale_chain_samples_as_grey():
    texture.MMTexture(_image('L')).bind()
    swizzled = [int(gl.glGetTexParameteriv(gl.GL_TEXTURE_2D, parameter))
                for parameter in (gl.GL_TEXTURE_SWIZZLE_R, gl.GL_TEXTURE_SWIZZLE_G,
                                  gl.GL_TEXTURE_SWIZZLE_B)]
    assert swizzled == [gl.GL_RED] * 3
    assert _level_width(1) == 4
